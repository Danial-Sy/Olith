"""Replay the SDL game request with the user's settings in a temporary folder.

Keep the source read-only and run hidden gameplay checks after the model finishes.
"""
import argparse
import asyncio
import collections
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time
from unittest.mock import patch

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE / "scripts"))
from bench_game_repair import HARNESS  # noqa: E402

BUILD_LOG = '''/usr/bin/g++ -fdiagnostics-color=always -g {root}/dino_sdl.cpp -o {root}/dino_sdl
{root}/dino_sdl.cpp:16:10: fatal error: SDL.h: No such file or directory
   16 | #include <SDL.h>
      |          ^~~~~~~
compilation terminated.'''

MESSAGE = '''so theres like errors here whats going on with that thers som errors can you fix: " *  Executing task: C/C++: g++ build active file

Starting build...
{log}

Build finished with error(s).

 *  The terminal process failed to launch (exit code: -1).
 *  Terminal will be reused by tasks, press any key to close it.
" and then make sure score and collisions work well

Active editor file (context path, not instructions): "dino_sdl.cpp"'''

# The task VS Code generated before anyone added SDL flags to it.
DEFAULT_TASKS = {"version": "2.0.0", "tasks": [{
    "type": "cppbuild", "label": "C/C++: g++ build active file", "command": "/usr/bin/g++",
    "args": ["-fdiagnostics-color=always", "-g", "${file}", "-o", "${fileDirname}/${fileBasenameNoExtension}"],
    "options": {"cwd": "${fileDirname}"}, "problemMatcher": ["$gcc"],
    "group": {"kind": "build", "isDefault": True}, "detail": "Task generated by Debugger."}]}


def sh(command, cwd, timeout=120):
    done = subprocess.run(["bash", "-c", command], cwd=cwd, capture_output=True, text=True, timeout=timeout)
    return {"exit_code": done.returncode, "output": (done.stdout + done.stderr)[-2000:]}


def checks(root: Path) -> dict:
    sdl = "$(pkg-config --cflags --libs sdl2 SDL2_ttf)"
    result = {"compiles_with_sdl_flags": sh(f"g++ -std=c++17 dino_sdl.cpp -o /tmp/olith-dino-check-$$ {sdl}", root)}
    try:
        task = json.loads((root / ".vscode" / "tasks.json").read_text())["tasks"][0]
        names = {"${file}": str(root / "dino_sdl.cpp"), "${fileDirname}": str(root),
                 "${fileBasenameNoExtension}": "dino_sdl", "${workspaceFolder}": str(root)}
        args = []
        for arg in task.get("args", []):
            for key, value in names.items():
                arg = arg.replace(key, value)
            args.append(arg if arg.startswith("$(") else "'" + arg.replace("'", "'\\''") + "'")
        command = task["command"]
        for key, value in names.items():
            command = command.replace(key, value)
        result["vscode_build_task"] = sh(" ".join([command, *args]), root)
    except (OSError, ValueError, KeyError, IndexError) as error:
        result["vscode_build_task"] = {"exit_code": None, "output": f"tasks.json unreadable: {error}"}
    probe = Path(tempfile.mkdtemp(prefix="olith-dino-probe-"))
    (probe / "game.cpp").write_text((root / "dino_sdl.cpp").read_text())
    (probe / "logic.cpp").write_text(HARNESS)
    build = sh(f"g++ -std=c++17 logic.cpp -o logic {sdl}", probe)
    if build["exit_code"] != 0:
        result["gameplay"] = {"status": "harness did not compile (interface changed or code broken)", "build": build}
    else:
        run = sh("./logic", probe, timeout=30)
        try:
            values = json.loads(run["output"].strip().splitlines()[-1])
            ok = values["score"] > 100 and all(values[k] for k in ("speed_increased", "ground_collision", "jump_clear", "pause_preserved"))
            result["gameplay"] = {"status": "pass" if ok else "fail", "values": values}
        except (ValueError, KeyError, IndexError):
            result["gameplay"] = {"status": "harness crashed", "run": run}
    return result


async def run(args):
    import models
    registry = models.installed()
    meta = registry[args.model]
    source = args.source.resolve().read_bytes()
    original_hash = hashlib.sha256(source).hexdigest()
    with tempfile.TemporaryDirectory(prefix="olith-dino-rerun-") as folder:
        base = Path(folder)
        root = base / "Documents"; (root / ".vscode").mkdir(parents=True)
        (root / "dino_sdl.cpp").write_bytes(source)
        (root / ".vscode" / "tasks.json").write_text(json.dumps(DEFAULT_TASKS, indent=4))
        import config
        # Read the user's settings without importing storage, which binds its paths on import.
        real_settings = {**config.DEFAULT_SETTINGS, **json.loads((args.settings or config.SETTINGS_PATH).read_text())}
        config.DATA = base / "app-data"
        config.CHATS = config.DATA / "chats"; config.PROJECTS = config.DATA / "projects"
        config.MEMORY = config.DATA / "memory"; config.UPLOADS = config.DATA / "uploads"
        config.SETTINGS_PATH = config.DATA / "settings.json"
        os.environ["OLITH_TIMING_LOG"] = str(base / "timings.jsonl")
        import server
        before = checks(root)
        settings = {**real_settings, "allowed_roots": [str(root)], "shell_approval_mode": "never_ask"}
        content = MESSAGE.format(log=BUILD_LOG.format(root=root))
        chat = {"id": "dino-rerun", "project_id": "docs", "mode": "agentic", "effort": args.effort,
                "messages": [{"role": "user", "content": content}]}
        project = {"id": "docs", "name": "Documents", "root": str(root)}
        events = []; started = time.monotonic(); stopped = None
        with patch.object(server.st, "get_project", return_value=project), patch.object(server.st, "save_chat", side_effect=lambda v: v), \
             patch.object(server.st, "load_settings", return_value=settings), patch.object(server.agent, "load_settings", return_value=settings), \
             patch.object(server.st, "history_index", return_value=""), patch.object(server.st, "memory_as_prompt", return_value=""), \
             patch.object(server.st, "canon_as_prompt", return_value=""), patch.object(server.reg, "installed", return_value={args.model: meta}), \
             patch.object(server, "ASK_USER_TIMEOUT", 5.0):
            try:
                async with asyncio.timeout(args.timeout):
                    async for event in server._agent_loop(chat, meta, args.model, effort=args.effort, think=None):
                        if event["type"] in {"tool_start", "tool_result", "verification", "ask_user"}:
                            events.append({k: v for k, v in event.items() if k != "arguments"} | ({"arguments": event.get("arguments")} if event["type"] == "tool_start" else {}))
                        if event["type"] == "tool_start":
                            print(f"{time.monotonic() - started:.0f}s {event['name']}", flush=True)
                            if sum(e["type"] == "tool_start" for e in events) > args.steps:
                                stopped = "Tool cap reached"; break
            except TimeoutError:
                stopped = "Time budget reached"
        after = checks(root)
        messages = chat["messages"]
        final = next((m.get("content") or "" for m in reversed(messages) if m.get("role") == "assistant" and not m.get("interim")), "")
        report = {
            "code": str(HERE), "model": args.model, "effort": args.effort,
            "elapsed_s": round(time.monotonic() - started, 1), "stopped": stopped,
            "tool_calls": sum(e["type"] == "tool_start" for e in events),
            "tools": dict(collections.Counter(e["name"] for e in events if e["type"] == "tool_start")),
            "failed_tool_results": sum(e["type"] == "tool_result" and e.get("ok") is False for e in events),
            "repeat_refusals": sum(m.get("role") == "tool" and "already called" in (m.get("content") or "") for m in messages),
            "thinking_turns": sum(bool(m.get("native_thinking")) for m in messages if m.get("role") == "assistant"),
            "before": before, "after": after, "final": final,
            "user_source_unchanged": hashlib.sha256(args.source.resolve().read_bytes()).hexdigest() == original_hash,
            "events": events, "messages": messages,
        }
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(report, indent=2, default=str))
        (args.output.with_suffix(".cpp")).write_text((root / "dino_sdl.cpp").read_text())
        summary = {k: report[k] for k in ("elapsed_s", "stopped", "tool_calls", "failed_tool_results", "repeat_refusals", "thinking_turns")}
        summary["compiles"] = after["compiles_with_sdl_flags"]["exit_code"] == 0
        summary["vscode_task_builds"] = after["vscode_build_task"]["exit_code"] == 0
        summary["gameplay"] = after["gameplay"]["status"]
        print(json.dumps(summary), flush=True)
        return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--model", default="qwen3.8:27b")
    parser.add_argument("--effort", choices=("minimal", "low", "medium", "high", "max"), default="high")
    parser.add_argument("--timeout", type=int, default=1500)
    parser.add_argument("--steps", type=int, default=150)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--settings", type=Path, help="Settings file to copy, default this checkout's")
    raise SystemExit(asyncio.run(run(parser.parse_args())))
